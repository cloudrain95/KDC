def safe_get(url, params, timeout=20):
    for i in range(2):
        try:
            return requests.get(url, params=params, headers=HEADERS, timeout=timeout)
        except requests.exceptions.Timeout:
            if i == 0:
                time.sleep(2)
            else:
                raise

